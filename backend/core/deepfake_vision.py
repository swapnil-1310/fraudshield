def _pil_to_base64(pil_img: Image.Image, fmt: str = "JPEG") -> str:
    """Convert PIL image to base64 string."""
    buf = BytesIO()
    pil_img.save(buf, format=fmt, quality=85)
    return base64.b64encode(buf.getvalue()).decode("utf-8")


def _scan_frame_for_watermarks(frame_bgr: np.ndarray) -> Dict[str, Any]:
    """
    Layer 1: Local OCR watermark scanning.
    Disabled in this version because without Tesseract OCR, relying on OpenCV 
    edge density and variance causes too many false positives on flat backgrounds 
    or random text (capping score at 88%).
    We now rely entirely on Gemini Vision (Layer 2) for accurate watermark & text detection.
    """
    return {"found": False}


def _gemini_vision_analyze_frame(frame_bgr: np.ndarray) -> Optional[Dict[str, Any]]:
    """
    Layer 2: Send a video frame to Gemini Vision for deep visual authenticity analysis.
    Checks for: AI watermarks, synthetic face artifacts, lip-sync issues, unnatural textures.
    """
    if not HAS_GEMINI_VISION or not config.GEMINI_API_KEY:
        return None

    try:
        frame_rgb = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2RGB)
        pil_img = Image.fromarray(frame_rgb)

        # Resize for API efficiency (max 1024px on longest side)
        max_dim = 1024
        ratio = min(max_dim / pil_img.width, max_dim / pil_img.height, 1.0)
        if ratio < 1.0:
            pil_img = pil_img.resize(
                (int(pil_img.width * ratio), int(pil_img.height * ratio)),
                Image.LANCZOS
            )

        prompt = """You are a forensic visual media analyst specializing in AI-generated content detection.

Analyze this video frame for ALL of the following indicators:

1. AI WATERMARKS & BRANDING: Look at ALL corners (top-left, top-right, bottom-left, bottom-right) and edges for any text, logos, or branding from AI generators like: Synthesia, HeyGen, D-ID, Sora, Runway, Pika, Kling, Luma, InVideo, Fliki, "Created with AI", "AI Generated", watermark overlays, trial/beta badges.

2. SYNTHETIC FACE ARTIFACTS: Unnatural skin smoothing, plastic-like texture, missing pores, floating teeth, asymmetric eyes, hair boundary glitches, ear deformation, inconsistent lighting on face vs background.

3. LIP-SYNC & MOTION: Lips not matching expected speech, robotic jaw movements, static facial expressions, unnaturally smooth head movements, avatar-style animation.

4. BACKGROUND ANOMALIES: Blurred/static backgrounds, warping around head edges, inconsistent depth of field, repeated patterns.

5. OVERALL ASSESSMENT: Does this look like a real human recording OR an AI-generated avatar/deepfake?

Respond ONLY with valid JSON (no markdown, no extra text):
{"is_ai_generated": true_or_false, "confidence": 0.00_to_1.00, "watermark_detected": "name of platform or none", "watermark_text": "exact text seen or none", "artifacts_found": ["artifact 1", "artifact 2"], "reasoning": "1-2 sentence explanation"}"""

        if _gemini_client and _gemini_client != "legacy":
            # New google-genai SDK
            img_bytes = BytesIO()
            pil_img.save(img_bytes, format="JPEG", quality=85)
            img_bytes.seek(0)

            response = _gemini_client.models.generate_content(
                model="gemini-3.6-flash",
                contents=[
                    {"inline_data": {"mime_type": "image/jpeg", "data": base64.b64encode(img_bytes.read()).decode()}},
                    prompt
                ],
                config={"temperature": 0.1, "max_output_tokens": 512}
            )
            raw = response.text.strip()

        elif _gemini_client == "legacy":
            import google.generativeai as genai_legacy
            model = genai_legacy.GenerativeModel("gemini-3.6-flash")
            response = model.generate_content(
                [pil_img, prompt],
                generation_config={"temperature": 0.1, "max_output_tokens": 512}
            )
            raw = response.text.strip()
        else:
            return None

        # Parse JSON response robustly
        data = {}
        try:
            # Try to parse the raw string directly first
            data = json.loads(raw)
        except Exception:
            try:
                # Try to extract from markdown code blocks
                m2 = re.search(r"```(?:json)?\s*(\{[\s\S]*?\})\s*```", raw)
                if m2:
                    data = json.loads(m2.group(1))
                else:
                    # Try to extract first JSON-like object
                    m = re.search(r"\{[\s\S]*\}", raw)
                    if m:
                        data = json.loads(m.group(0))
            except Exception as e:
                print(f"[DeepfakeVision] JSON parse error: {e}. Raw: {raw[:100]}")

        return {
            "is_ai": bool(data.get("is_ai_generated", False)),
            "ai_confidence": float(data.get("confidence", 0.5)),
            "watermark_detected": str(data.get("watermark_detected", "none")),
            "watermark_text": str(data.get("watermark_text", "none")),
            "artifacts": data.get("artifacts_found", []),
            "reasoning": str(data.get("reasoning", ""))
        }

    except Exception as e:
        print(f"[DeepfakeVision] Gemini Vision frame analysis note: {e}")
        return None


class VisualDeepfakeDetector:
    """
    3-Layer Visual Deepfake Detector:
      Layer 1: AI Watermark & Signature Scanner (OpenCV edge/text detection)
      Layer 2: Gemini Vision Multimodal Frame Inspector
      Layer 3: PyTorch ViT Model / OpenCV Heuristic Fallback
    """

    def __init__(self, model_name: str = "SadraCoding/SDXL-Deepfake-Detector"):
        self.model_name = model_name
        self.device = "cuda" if HAS_TRANSFORMERS and torch.cuda.is_available() else "cpu"
        self.model = None
        self.processor = None
        self._load_model()

    def _load_model(self):
        if config.HUGGINGFACE_API_KEY:
            print(f"[DeepfakeVision] HuggingFace API key found. Will use serverless inference for '{self.model_name}'.")
        else:
            print("[DeepfakeVision] No HuggingFace API key. Using Gemini Vision + OpenCV fallback.")

    def analyze_frame(self, frame_bgr: np.ndarray) -> Dict[str, Any]:
        """Analyze a single BGR frame through the 3-layer pipeline."""
        if frame_bgr is None or frame_bgr.size == 0:
            return {"is_ai": False, "ai_confidence": 0.0, "watermark": "none", "method": "none"}

        # ── Layer 1: Watermark Scan (instant, zero-cost) ─────────────────────
        wm = _scan_frame_for_watermarks(frame_bgr)
        if wm.get("found"):
            return {
                "is_ai": True,
                "ai_confidence": max(0.85, wm.get("confidence", 0.85)),
                "watermark": wm.get("detail", "AI watermark detected"),
                "method": "watermark_scan"
            }

        # ── Layer 2: HuggingFace Inference API (SOTA ViT Model) ──────────────
        if config.HUGGINGFACE_API_KEY:
            try:
                import requests
                frame_rgb = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2RGB)
                pil_img = Image.fromarray(frame_rgb)
                
                # Resize for API efficiency to save bandwidth
                pil_img.thumbnail((512, 512))
                img_bytes = BytesIO()
                pil_img.save(img_bytes, format="JPEG", quality=85)
                
                headers = {"Authorization": f"Bearer {config.HUGGINGFACE_API_KEY}"}
                api_url = f"https://api-inference.huggingface.co/models/{self.model_name}"
                
                response = requests.post(api_url, headers=headers, data=img_bytes.getvalue(), timeout=5)
                
                if response.status_code == 200:
                    results = response.json()
                    # Results typically list dicts: [{'label': 'fake', 'score': 0.9}, ...]
                    ai_conf = 0.0
                    for res in results:
                        if any(kw in str(res.get('label', '')).lower() for kw in ['fake', 'ai', 'synthetic', 'generated']):
                            ai_conf = float(res.get('score', 0.0))
                            break
                    
                    return {
                        "is_ai": ai_conf >= config.DEEPFAKE_THRESHOLD,
                        "ai_confidence": round(ai_conf, 4),
                        "watermark": "none",
                        "method": "hf_inference_api"
                    }
            except Exception as e:
                print(f"[DeepfakeVision] HF API inference note: {e}")

        # ── Layer 3: OpenCV Heuristic (texture + frequency analysis) ─────────
        gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
        h, w = gray.shape

        # Multi-signal heuristic scoring
        score = 0.05 # Baseline
        signals = []

        # 3a. Laplacian variance (sharpness/texture complexity)
        lap_var = cv2.Laplacian(gray, cv2.CV_64F).var()
        if lap_var < 30.0:
            score += 0.20
            signals.append("very_smooth_texture")
        elif lap_var < 80.0:
            score += 0.10
            signals.append("smooth_texture")

        # 3b. Color uniformity (AI images have unnaturally uniform color patches)
        hsv = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2HSV)
        sat_std = float(np.std(hsv[:, :, 1]))
        if sat_std < 20.0:
            score += 0.10
            signals.append("low_saturation_variance")

        # 3c. Edge coherence (AI faces have overly clean edges)
        edges = cv2.Canny(gray, 80, 200)
        edge_ratio = np.sum(edges > 0) / edges.size
        if edge_ratio < 0.02:
            score += 0.15
            signals.append("unnaturally_clean_edges")
        elif edge_ratio > 0.40:
            score += 0.05
            signals.append("excessive_edge_artifacts")

        # 3d. Symmetry check on center face region (AI faces are often too symmetric)
        center_strip = gray[h // 4: 3 * h // 4, w // 4: 3 * w // 4]
        if center_strip.size > 0:
            left_half = center_strip[:, :center_strip.shape[1] // 2]
            right_half = cv2.flip(center_strip[:, center_strip.shape[1] // 2:], 1)
            min_w = min(left_half.shape[1], right_half.shape[1])
            if min_w > 0:
                diff = np.mean(np.abs(left_half[:, :min_w].astype(float) - right_half[:, :min_w].astype(float)))
                if diff < 5.0:
                    score += 0.15
                    signals.append("excessive_facial_symmetry")

        # 3e. Noise pattern analysis (AI images have uniform noise, real cameras have sensor noise)
        noise = cv2.absdiff(gray, cv2.GaussianBlur(gray, (5, 5), 0))
        noise_std = float(np.std(noise))
        if noise_std < 2.0:
            score += 0.10
            signals.append("missing_sensor_noise")

        score = min(round(score, 4), 1.0)

        return {
            "is_ai": score >= config.DEEPFAKE_THRESHOLD,
            "ai_confidence": score,
            "watermark": "none",
            "method": "opencv_heuristic",
            "signals": signals
        }

    def analyze_video(self, video_path: str, max_frames: int = 150) -> Dict[str, Any]:
        """
        Full 3-layer video analysis pipeline:
        1. Sample frames every 1.5s
        2. Run each through watermark scan + ViT/heuristic analysis
        3. Send 3 key frames to Gemini Vision for deep multimodal reasoning
        4. Ensemble all scores into final verdict
        """
        if not os.path.exists(video_path):
            return {"is_deepfake": False, "score": 0.0, "frames_analyzed": 0,
                    "summary": "Video file not found.", "watermark_detected": "none",
                    "gemini_reasoning": "", "artifacts": []}

        cap = cv2.VideoCapture(video_path)
        if not cap.isOpened():
            return {"is_deepfake": False, "score": 0.0, "frames_analyzed": 0,
                    "summary": "Could not open video.", "watermark_detected": "none",
                    "gemini_reasoning": "", "artifacts": []}

        fps = cap.get(cv2.CAP_PROP_FPS) or 25
        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
        sample_interval = max(1, int(fps * 1.5))

        frame_idx = 0
        analyzed_count = 0
        ai_confidences = []
        watermark_hits = []
        keyframes_for_gemini = []  # Store 3 representative frames

        while True:
            ret, frame = cap.read()
            if not ret:
                break
            if frame_idx % sample_interval == 0:
                result = self.analyze_frame(frame)
                ai_confidences.append(result["ai_confidence"])
                analyzed_count += 1

                # Collect watermark detections
                if result.get("watermark", "none") != "none":
                    watermark_hits.append(result["watermark"])

                # Save keyframes for Gemini Vision (first, middle, last sampled)
                if len(keyframes_for_gemini) < 3:
                    keyframes_for_gemini.append(frame.copy())
                elif analyzed_count == max_frames // 2:
                    keyframes_for_gemini[1] = frame.copy()
                elif analyzed_count > 2:
                    keyframes_for_gemini[2] = frame.copy()

                if analyzed_count >= max_frames:
                    break
            frame_idx += 1

        cap.release()

        if not ai_confidences:
            return {"is_deepfake": False, "score": 0.0, "frames_analyzed": 0,
                    "summary": "No frames extracted.", "watermark_detected": "none",
                    "gemini_reasoning": "", "artifacts": []}

        # ── Compute base score from per-frame analysis ────────────────────────
        avg_score = float(np.mean(ai_confidences))
        max_score = float(np.max(ai_confidences))
        base_score = round(0.55 * avg_score + 0.45 * max_score, 4)

        # ── Watermark boost (if detected in any frame) ────────────────────────
        watermark_detected = "none"
        if watermark_hits:
            watermark_detected = watermark_hits[0]
            base_score = max(base_score, 0.88)  # Watermark = minimum 88%

        # ── Gemini Vision deep analysis on keyframes ──────────────────────────
        gemini_reasoning = ""
        gemini_artifacts = []
        gemini_watermark = "none"
        gemini_score = None

        if HAS_GEMINI_VISION and keyframes_for_gemini:
            # Analyze the middle keyframe (most representative)
            target_frame = keyframes_for_gemini[len(keyframes_for_gemini) // 2]
            gemini_result = _gemini_vision_analyze_frame(target_frame)

            if gemini_result:
                gemini_score = gemini_result["ai_confidence"]
                gemini_reasoning = gemini_result.get("reasoning", "")
                gemini_artifacts = gemini_result.get("artifacts", [])

                wm_name = gemini_result.get("watermark_detected", "none")
                wm_text = gemini_result.get("watermark_text", "none")

                if wm_name and wm_name.lower() not in ("none", "null", "n/a", ""):
                    gemini_watermark = f"{wm_name}"
                    if wm_text and wm_text.lower() not in ("none", "null", "n/a", ""):
                        gemini_watermark += f" ('{wm_text}')"
                    # Watermark from Gemini Vision = very high confidence
                    base_score = max(base_score, 0.95)
                    watermark_detected = gemini_watermark

        # ── Final ensemble score ──────────────────────────────────────────────
        if gemini_score is not None:
            # Blend: 40% base per-frame + 60% Gemini Vision deep analysis
            final_score = round(0.40 * base_score + 0.60 * gemini_score, 4)
            # But watermark detection overrides to at least 0.90
            if watermark_detected != "none":
                final_score = max(final_score, 0.90)
        else:
            final_score = base_score

        final_score = min(final_score, 1.0)
        is_deepfake = final_score >= config.DEEPFAKE_THRESHOLD

        # ── Build summary ─────────────────────────────────────────────────────
        parts = []
        if is_deepfake:
            parts.append(f"AI Manipulated / Deepfake Video Detected (Confidence: {final_score:.0%})")
        else:
            parts.append(f"Authentic Visual Media (Deepfake Score: {final_score:.0%})")

        if watermark_detected != "none":
            parts.append(f"AI Watermark Identified: {watermark_detected}")

        if gemini_reasoning:
            parts.append(f"Visual Forensics: {gemini_reasoning}")

        summary_icon = "🚨" if is_deepfake else "✅"
        summary = f"{summary_icon} {' | '.join(parts)}"

        return {
            "is_deepfake": is_deepfake,
            "score": final_score,
            "frames_analyzed": analyzed_count,
            "summary": summary,
            "watermark_detected": watermark_detected,
            "gemini_reasoning": gemini_reasoning,
            "artifacts": gemini_artifacts
        }
